/**
 * Get localized strings for a language, with fallback to Hindi (for Indic) or English
 */
export const getStrings = (langCode = 'en') => {
  const norm = String(langCode).toLowerCase().split('-')[0];
  if (LOCALIZED_STRINGS[norm]) {
    return LOCALIZED_STRINGS[norm];
  }
  // Odia alias
  if (norm === 'od') {
    return LOCALIZED_STRINGS.or;
  }
  return LOCALIZED_STRINGS.en;
};

/**
 * Validate that a generated response contains ZERO forbidden English boilerplate
 * when the target language is NOT English.
 * Returns { valid: boolean, reason?: string }
 */
export const validateResponseLanguage = ({ text = '', targetLang = 'en', targetSpeechCode = 'en-IN' }) => {
  const norm = String(targetLang).toLowerCase().split('-')[0];
  if (norm === 'en') {
    return { valid: true };
  }

  // Forbidden English boilerplate phrases that must NEVER leak into non-English responses
  const forbiddenEnglishPhrases = [
    /tell\s+me\s+more\s+about/i,
    /tell\s+me\s+about\s+\d/i,
    /which\s+one\s+is\s+nearby/i,
    /would\s+you\s+like\s+more\s+details/i,
    /would\s+you\s+like\s+to\s+know/i,
    /here\s+are\s+some\s+options/i,
    /here\s+are\s+the\s+available/i,
    /for\s+more\s+information\s+reply/i,
    /please\s+select\s+one/i,
    /click\s+here\s+to/i,
    /enter\s+your\s+choice/i,
    /tell\s+me\s+your\s+location/i,
    /feel\s+free\s+to\s+message/i,
    /have\s+a\s+great\s+day/i
  ];

  for (const pattern of forbiddenEnglishPhrases) {
    if (pattern.test(text)) {
      return {
        valid: false,
        reason: `Detected forbidden English boilerplate phrase: ${pattern.toString()}`
      };
    }
  }

  // Check script sanity: For Indic languages, make sure there is sufficient native script content
  // Allowed Latin exceptions: Brand / Program acronyms like PMEGP, PM-AJAY, PMKVY, DIC, NSQF, QP, etc.
  const indicScriptRegexes = {
    hi: /[\u0900-\u097F]/, // Devanagari
    mr: /[\u0900-\u097F]/,
    ne: /[\u0900-\u097F]/,
    sa: /[\u0900-\u097F]/,
    mai: /[\u0900-\u097F]/,
    kok: /[\u0900-\u097F]/,
    brx: /[\u0900-\u097F]/,
    doi: /[\u0900-\u097F]/,
    bn: /[\u0980-\u09FF]/, // Bengali
    as: /[\u0980-\u09FF]/, // Assamese
    ta: /[\u0B80-\u0BFF]/, // Tamil
    te: /[\u0C00-\u0C7F]/, // Telugu
    kn: /[\u0C80-\u0CFF]/, // Kannada
    ml: /[\u0D00-\u0D7F]/, // Malayalam
    gu: /[\u0A80-\u0AFF]/, // Gujarati
    pa: /[\u0A00-\u0A7F]/, // Gurmukhi
    or: /[\u0B00-\u0B7F]/, // Odia
    od: /[\u0B00-\u0B7F]/,
    ur: /[\u0600-\u06FF]/, // Perso-Arabic
    ks: /[\u0600-\u06FF\u0900-\u097F]/,
    sd: /[\u0600-\u06FF]/,
    sat: /[\u1C50-\u1C7F]/, // Ol Chiki
    mni: /[\u0980-\u09FF\uABC0-\uABFF]/
  };

  const expectedScript = indicScriptRegexes[norm];
  if (expectedScript) {
    const hasScript = expectedScript.test(text);
    if (!hasScript) {
      return {
        valid: false,
        reason: `Response lacks expected native script characters for language '${norm}'.`
      };
    }
  }

  return { valid: true };
};
